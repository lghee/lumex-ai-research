import assert from 'node:assert/strict';
import {collectStandbySlice,standbyUrl,standbyR2Key,decideRestStandby,lastClosedSlice} from '../src/order-flow-futures-rest-standby.mjs';
const S=10000, now=Date.UTC(2026,10,21,11,59,50);
const slice=now-3*S, quote={BTC_USDT:0.0001};
assert.equal(new URL(standbyUrl('BTC',slice)).searchParams.get('contract'),'BTC_USDT');
assert.equal(new URL(standbyUrl('BTC',slice)).searchParams.has('offset'),false);
assert.equal(new URL(standbyUrl('BTC',slice)).searchParams.has('page'),false);
assert.equal(new URL(standbyUrl('BTC',slice)).searchParams.get('from'),String(slice/1000));
assert.match(standbyR2Key('BTC',slice),/BTC\/\d+\.json$/);
assert.equal(lastClosedSlice(now),now-S);
const row=(id,at)=>({contract:'BTC_USDT',id:String(id),price:'100000',size:'-1.25',
 create_time_ms:at/1000});
let count=0;
const f=async (url,opts)=>{
 count++;
 assert.equal(opts.headers['X-Gate-Size-Decimal'],'1');
 return new Response(JSON.stringify([row(11,slice+2500),row(12,slice+5000)]));
};
const x=await collectStandbySlice('BTC',slice,quote,{now,fetchFn:f});
assert.equal(count,1);assert.equal(x.ok,true);assert.equal(x.status,'observed_rest_trades');
assert.equal(x.observed_trades,2);
assert.equal(x.last_trade_ms,slice+5000);
assert.equal(x.buy_quote_usdt,0);
assert.ok(Math.abs(x.sell_quote_usdt-25)<1e-10);
assert.equal(x.exchange_trade_completeness_verified,false);
assert.equal(x.customer_launch_ready,false);
assert.equal(x.websocket_merged,false);
assert.equal((await collectStandbySlice('BTC',slice,{}, {now})).status,'contract_unit_unverified');
assert.equal((await collectStandbySlice('BTC',now,quote,{now})).status,'out_of_range');
assert.equal((await collectStandbySlice('BTC',slice,quote,{now,fetchFn:async()=>new Response(JSON.stringify([row(11,slice-1000)]))})).status,'wrong_source_or_time');
assert.equal((await collectStandbySlice('BTC',slice,quote,{now,fetchFn:async()=>new Response(JSON.stringify([row(11,slice+1500),row(11,slice+2000)]))})).status,'duplicate_trade_id');
assert.equal((await collectStandbySlice('BTC',slice,quote,{now,fetchFn:async()=>new Response(JSON.stringify(Array(1000).fill(row(10,slice+2000))))})).status,'possibly_truncated');
const empty=await collectStandbySlice('BTC',slice,quote,{now,fetchFn:async()=>new Response('[]')});
assert.equal(empty.ok,true);assert.equal(empty.status,'empty_rest_response');
assert.equal(empty.observed_trades,0);
assert.equal(empty.exchange_trade_completeness_verified,false);
const f2=decideRestStandby({futures_1006_recent_ms:[now-160000,now-120000,now-5000]},now);
assert.equal(f2.use_rest_standby,true);
assert.equal(decideRestStandby({futures_1006_recent_ms:[now-160000,now-120000]},now).use_rest_standby,false);
assert.equal(decideRestStandby({futures_ws_circuit_until:now+30000},now).use_rest_standby,true);
console.log('PASS Phase36 Gate futures standby time slices, 1006 circuit, precise size, fail-closed R2 provenance');
